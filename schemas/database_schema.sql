-- ============================================================================
-- OpenClaw Trading System — PostgreSQL Database Schema
-- ============================================================================
-- This schema supports the full trading lifecycle: signals, trades, performance,
-- risk events, system health, and self-improvement audit trail.
-- ============================================================================

-- Enable extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "timescaledb";  -- Optional: for time-series optimization

-- ============================================================================
-- 1. SIGNALS TABLE
-- Records every signal generated by OpenClaw, regardless of outcome.
-- ============================================================================
CREATE TABLE signals (
    id                  UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    signal_id           VARCHAR(100) UNIQUE NOT NULL,
    signal_type         VARCHAR(20) NOT NULL,  -- ENTRY, EXIT, MODIFY, PARTIAL_CLOSE
    asset               VARCHAR(20) NOT NULL,
    direction           VARCHAR(20) NOT NULL,
    entry_price_ref     DECIMAL(20, 8),
    stop_loss           DECIMAL(20, 8),
    take_profit_1       DECIMAL(20, 8),
    take_profit_2       DECIMAL(20, 8),
    lot_size            DECIMAL(10, 4),
    risk_percent        DECIMAL(6, 4),
    risk_dollars        DECIMAL(12, 2),
    risk_reward_ratio   DECIMAL(6, 2),
    signal_score        DECIMAL(4, 2),
    regime              VARCHAR(30),
    regime_confidence   DECIMAL(4, 2),
    mtf_alignment_score DECIMAL(4, 2),
    mtf_alignment_quality VARCHAR(10),
    volatility_state    VARCHAR(20),
    atr_current         DECIMAL(20, 8),
    atr_percentile      DECIMAL(5, 1),
    adx_value           DECIMAL(6, 2),
    strategy_id         VARCHAR(50),
    operational_mode    VARCHAR(20),
    status              VARCHAR(30) NOT NULL DEFAULT 'GENERATED',
    -- Status: GENERATED, PUBLISHED, ACKNOWLEDGED, FILLED, REJECTED, FILTERED, EXPIRED
    rejection_reason    VARCHAR(100),
    generation_latency_ms INTEGER,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    published_at        TIMESTAMPTZ,
    acknowledged_at     TIMESTAMPTZ,
    executed_at         TIMESTAMPTZ,
    metadata            JSONB
);

CREATE INDEX idx_signals_asset ON signals(asset);
CREATE INDEX idx_signals_created ON signals(created_at);
CREATE INDEX idx_signals_status ON signals(status);
CREATE INDEX idx_signals_regime ON signals(regime);


-- ============================================================================
-- 2. TRADES TABLE
-- Records every completed trade with full metrics.
-- ============================================================================
CREATE TABLE trades (
    id                      UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    trade_id                VARCHAR(100) UNIQUE NOT NULL,
    signal_id               VARCHAR(100) REFERENCES signals(signal_id),
    asset                   VARCHAR(20) NOT NULL,
    direction               VARCHAR(10) NOT NULL,
    entry_time              TIMESTAMPTZ NOT NULL,
    exit_time               TIMESTAMPTZ,
    hold_duration_minutes   INTEGER,
    entry_price             DECIMAL(20, 8) NOT NULL,
    exit_price              DECIMAL(20, 8),
    stop_loss               DECIMAL(20, 8) NOT NULL,
    take_profit             DECIMAL(20, 8),
    lot_size                DECIMAL(10, 4) NOT NULL,
    risk_percent            DECIMAL(6, 4) NOT NULL,
    risk_dollars            DECIMAL(12, 2) NOT NULL,

    -- P&L
    pnl_dollars             DECIMAL(12, 2),
    pnl_percent             DECIMAL(8, 4),
    pnl_pips                DECIMAL(10, 2),
    actual_rr               DECIMAL(6, 2),
    planned_rr              DECIMAL(6, 2),

    -- Excursion analysis
    max_favorable_excursion DECIMAL(20, 8),   -- Highest profit during trade
    max_adverse_excursion   DECIMAL(20, 8),   -- Worst drawdown during trade
    mfe_price               DECIMAL(20, 8),
    mae_price               DECIMAL(20, 8),

    -- Execution quality
    slippage_entry_points   DECIMAL(10, 2),
    slippage_exit_points    DECIMAL(10, 2),
    spread_at_entry         DECIMAL(10, 2),
    spread_at_exit          DECIMAL(10, 2),
    commission              DECIMAL(10, 4),
    swap                    DECIMAL(10, 4),

    -- Context
    regime_at_entry         VARCHAR(30),
    regime_at_exit          VARCHAR(30),
    signal_score            DECIMAL(4, 2),
    mtf_alignment_score     DECIMAL(4, 2),
    exit_reason             VARCHAR(50),
    -- EXIT_REASONS: TP1_HIT, TP2_HIT, SL_HIT, TRAILING_STOP, SIGNAL_EXIT,
    --              REGIME_SHIFT, EMERGENCY, MANUAL, BREAKEVEN_STOP

    strategy_id             VARCHAR(50),
    magic_number            INTEGER,
    mt5_ticket              BIGINT,
    notes                   TEXT,
    metadata                JSONB,

    -- Status
    status                  VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    -- OPEN, CLOSED, PARTIALLY_CLOSED
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_trades_asset ON trades(asset);
CREATE INDEX idx_trades_entry_time ON trades(entry_time);
CREATE INDEX idx_trades_exit_time ON trades(exit_time);
CREATE INDEX idx_trades_status ON trades(status);
CREATE INDEX idx_trades_regime ON trades(regime_at_entry);
CREATE INDEX idx_trades_direction ON trades(direction);


