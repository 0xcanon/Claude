-- ============================================================================
-- MATERIALIZED VIEWS FOR PERFORMANCE DASHBOARDS
-- ============================================================================

-- Hourly equity summary
CREATE MATERIALIZED VIEW IF NOT EXISTS equity_hourly AS
SELECT
    date_trunc('hour', created_at) AS hour,
    AVG(equity) AS avg_equity,
    MAX(equity) AS max_equity,
    MIN(equity) AS min_equity,
    (array_agg(equity ORDER BY created_at DESC))[1] AS close_equity
FROM equity_snapshots
GROUP BY date_trunc('hour', created_at)
ORDER BY hour;

-- Trade performance by asset (last 30 days)
CREATE MATERIALIZED VIEW IF NOT EXISTS asset_performance_30d AS
SELECT
    asset,
    COUNT(*) AS total_trades,
    SUM(CASE WHEN pnl_dollars > 0 THEN 1 ELSE 0 END) AS wins,
    SUM(CASE WHEN pnl_dollars <= 0 THEN 1 ELSE 0 END) AS losses,
    ROUND(SUM(CASE WHEN pnl_dollars > 0 THEN 1.0 ELSE 0 END) / NULLIF(COUNT(*), 0), 4) AS win_rate,
    SUM(pnl_dollars) AS total_pnl,
    AVG(pnl_dollars) AS avg_pnl,
    AVG(actual_rr) AS avg_rr,
    MAX(pnl_dollars) AS best_trade,
    MIN(pnl_dollars) AS worst_trade
FROM trades
WHERE exit_time >= NOW() - INTERVAL '30 days'
  AND status = 'CLOSED'
GROUP BY asset;

-- Trade performance by regime (last 30 days)
CREATE MATERIALIZED VIEW IF NOT EXISTS regime_performance_30d AS
SELECT
    regime_at_entry,
    COUNT(*) AS total_trades,
    ROUND(SUM(CASE WHEN pnl_dollars > 0 THEN 1.0 ELSE 0 END) / NULLIF(COUNT(*), 0), 4) AS win_rate,
    SUM(pnl_dollars) AS total_pnl,
    AVG(actual_rr) AS avg_rr
FROM trades
WHERE exit_time >= NOW() - INTERVAL '30 days'
  AND status = 'CLOSED'
GROUP BY regime_at_entry;


-- ============================================================================
-- UTILITY FUNCTIONS
-- ============================================================================

-- Function to refresh all materialized views
CREATE OR REPLACE FUNCTION refresh_dashboard_views()
RETURNS void AS $$
BEGIN
    REFRESH MATERIALIZED VIEW equity_hourly;
    REFRESH MATERIALIZED VIEW asset_performance_30d;
    REFRESH MATERIALIZED VIEW regime_performance_30d;
END;
$$ LANGUAGE plpgsql;
